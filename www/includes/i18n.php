}

function currentLanguage(): string
{
    if (isset($_GET['lang']) && array_key_exists($_GET['lang'], availableLanguages())) {
        $_SESSION['lang'] = $_GET['lang'];
    }

    return $_SESSION['lang'] ?? 'pt-BR';
}

